import { Hono } from 'hono';
import { Env, serverSupabaseKey } from './api_types';
import { errorMiddleware } from './middleware/errors';
import { healthRoutes } from './routes/health';
import { assistantRoutes } from './routes/business_assistant';
import { documentRoutes } from './routes/document_processing';
import { whatsappWebhookRoutes } from './routes/whatsapp_webhook';
import { inboxRoutes } from './routes/inbox';
import { accountsRoutes } from './routes/accounts';
import { SupabaseRuntimeRepository } from './agent-runtime/supabase_repository';
import { runAccountsAgent } from './agent-runtime/accounts_dispatcher';
import { tenderRoutes } from './routes/tenders';
import { runTenderAgent } from './agent-runtime/tender_dispatcher';
import { workforceRoutes } from './routes/workforce';
import { billingRoutes } from './routes/billing';
const app = new Hono<{ Bindings: Env }>();
app.use('*', errorMiddleware);
app.route('/api/v1', healthRoutes);
app.route('/api/v1', assistantRoutes);
app.route('/api/v1', documentRoutes);
app.route('/api/v1', whatsappWebhookRoutes);
app.route('/api/v1', inboxRoutes);
app.route('/api/v1', accountsRoutes);
app.route('/api/v1', tenderRoutes);
app.route('/api/v1', workforceRoutes);
app.route('/api/v1', billingRoutes);
export default app;
export const scheduled = async (_event: ScheduledEvent, env: Env, ctx: ExecutionContext) => {
  const repo = new SupabaseRuntimeRepository(env.SUPABASE_URL, serverSupabaseKey(env));
  const agents: any[] = await repo.listByFilter('agents', { agent_type_key: 'accounts_collections_agent', status: 'active' });
  for (const agent of agents) ctx.waitUntil(runAccountsAgent(repo, env, agent.organisation_id, agent, {}).catch(async () => { await repo.insert('collection_activity', agent.organisation_id, { activity_type: 'scheduled_run_failed', metadata: { agent_id: agent.id, source: 'system' } }).catch(() => undefined); }));
  const tenderAgents: any[] = await repo.listByFilter('agents', { agent_type_key: 'tender_agent', status: 'active' });
  for (const agent of tenderAgents) ctx.waitUntil(runTenderAgent(repo, env, agent.organisation_id, agent, {}).catch(() => undefined));
};
